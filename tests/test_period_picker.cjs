// Home-Assistant-style picker: functional presets, date navigation and responsive UI.
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const src=fs.readFileSync(path.join(__dirname,'..','custom_components','smartify_flow_card','frontend','smartify-flow-card.js'),'utf8');
const i=src.indexOf('function sfcLocalDate('),j=src.indexOf('function sfcHistoryPoints(',i);
assert.ok(i>=0&&j>i);
const p=vm.runInNewContext(src.slice(i,j)+'\n({preset:sfcPickerPreset,page:sfcPickerPage,label:sfcPickerLabel,validate:sfcValidatePeriod,presets:SFC_PERIOD_PRESETS})');
const obj=v=>JSON.parse(JSON.stringify(v));
const now=new Date(2026,10,12,18,0,0);
assert.deepEqual(p.presets.map(x=>x[0]),['today','yesterday','week','month','quarter','year','last7','last30','last365','last12']);
assert.deepEqual(obj(p.preset('today',now)),{start:'2026-11-12',end:'2026-11-12',mode:'today'});
assert.deepEqual(obj(p.preset('yesterday',now)),{start:'2026-11-11',end:'2026-11-11',mode:'yesterday'});
assert.deepEqual(obj(p.preset('week',now)),{start:'2026-11-09',end:'2026-11-12',mode:'week'});
assert.deepEqual(obj(p.preset('month',now)),{start:'2026-11-01',end:'2026-11-12',mode:'month'});
assert.deepEqual(obj(p.preset('quarter',now)),{start:'2026-10-01',end:'2026-11-12',mode:'quarter'});
assert.deepEqual(obj(p.preset('year',now)),{start:'2026-01-01',end:'2026-11-12',mode:'year'});
assert.deepEqual(obj(p.preset('last7',now)),{start:'2026-11-06',end:'2026-11-12',mode:'last7'});
assert.deepEqual(obj(p.preset('last30',now)),{start:'2026-10-14',end:'2026-11-12',mode:'last30'});
assert.deepEqual(obj(p.preset('last365',now)),{start:'2025-11-13',end:'2026-11-12',mode:'last365'});
assert.deepEqual(obj(p.preset('last12',now)),{start:'2025-12-01',end:'2026-11-12',mode:'last12'});
const month=p.preset('month',now),year=p.preset('year',now),week=p.preset('week',now);
assert.deepEqual(obj(p.page(month,'month',-1,now)),{start:'2026-10-01',end:'2026-10-31',mode:'month'});
assert.deepEqual(obj(p.page({start:'2026-10-01',end:'2026-10-31'},'month',1,now)),obj(month),'next month reaches the current, still-open month');
assert.deepEqual(obj(p.page(year,'year',-1,now)),{start:'2025-01-01',end:'2025-12-31',mode:'year'});
assert.deepEqual(obj(p.page({start:'2025-01-01',end:'2025-12-31'},'year',1,now)),obj(year));
assert.deepEqual(obj(p.page(week,'week',-1,now)),{start:'2026-11-02',end:'2026-11-08',mode:'week'});
assert.deepEqual(obj(p.page(p.preset('quarter',now),'quarter',-1,now)),{start:'2026-07-01',end:'2026-09-30',mode:'quarter'});
assert.deepEqual(obj(p.page(p.preset('last12',now),'last12',-1,now)),{start:'2024-12-01',end:'2025-11-30',mode:'last12'});
assert.deepEqual(obj(p.page({start:'2025-12-30',end:'2026-01-02'},null,-1,now)),{start:'2025-12-26',end:'2025-12-29',mode:null});
assert.equal(p.page(month,'month',1,now),null,'future months blocked');
assert.equal(p.page(p.preset('today',now),'today',1,now),null,'future days blocked');
assert.deepEqual(obj(p.page(p.preset('today',now),'today',-1,now)),{start:'2026-11-11',end:'2026-11-11',mode:'day'});
assert.equal(p.label(year,'year'),'2026');
assert.match(p.label(month,'month'),/November 2026/);
assert.equal(p.validate('2026-11-13','2026-11-13',now),null);
for(const value of ['history-picker','history-prev history-nav','history-next history-nav','history-calendar-days','history-presets','history-ok','history-cancel'])
  assert.ok(src.includes('class="'+value+'"'),'missing element '+value);
assert.match(src,/history-picker-content\{display:grid/,'desktop side presets');
assert.match(src,/@media\(max-width:520px\)/,'mobile preset scroller');
assert.match(src,/btn\.disabled=date>today/,'future dates disabled in calendar');
assert.match(src,/this\._loadHistory\(pending\.start,pending\.end,mode\)/,'confirm selection triggers history');
assert.match(src,/this\._historyMode='live'/,'live stays intact');
console.log('Period picker: 10 shortcuts, calendar page navigation, custom ranges, future guard and responsive UI passed');
