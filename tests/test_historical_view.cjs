// Historical smartify flow regression checks: fixed 15-min energy windows and stable dialog.
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const src=fs.readFileSync(path.join(__dirname,'..','custom_components','smartify_flow_card','frontend','smartify-flow-card.js'),'utf8');
const begin=src.indexOf('function sfcLocalDate('),end=src.indexOf('class SmartifyFlowCard extends HTMLElement',begin);
assert.ok(begin>=0&&end>begin,'history functions exist');
const h=vm.runInNewContext(src.slice(begin,end)+'\n({date:sfcLocalDate,bounds:sfcDateWindow,points:sfcHistoryPoints,delta:sfcEnergyDelta,peak:sfcQuarterPeak,verified:sfcVerifiedBoundaryEnergy})');
const one=300000,start=Date.parse('2026-11-03T18:00:00.000Z');
let samples=[];
for(let i=-1;i<=5;i++)samples.push({start:new Date(start+i*one).toISOString(),sum:20+i*.125});
const pts=h.points(samples,'kWh');
const peak=h.peak(pts,start,start+one*6);
assert.equal(peak.kw,1.5,'three five-minute increments of .125 kWh = 1.5 kW');
assert.equal(peak.from,start);
assert.equal(peak.to,start+900000);
assert.equal(h.peak(h.points(samples.filter(x=>x.start!==new Date(start-one).toISOString()),'kWh'),start,start+900000),null,'missing first boundary must not guess');
assert.equal(h.peak(h.points([{start:new Date(start-one).toISOString(),sum:2},{start:new Date(start).toISOString(),sum:2},{start:new Date(start+one).toISOString(),sum:1},{start:new Date(start+2*one).toISOString(),sum:4}],'kWh'),start,start+900000),null,'counter reset not treated as a peak');
const d=Date.parse('2026-11-03T00:00:00.000Z');
const daily=h.points([{start:new Date(d-3600000).toISOString(),sum:5},{start:new Date(d+23*3600000).toISOString(),sum:12}],'kWh');
assert.equal(h.delta(daily,d,d+86400000),7,'hourly energy is anchored to end-of-period rows');
assert.equal(h.delta(h.points([{start:new Date(d).toISOString(),sum:5}],'kWh'),d,d+86400000),null,'missing full-day boundary stays unavailable');
assert.equal(h.points([{start:new Date(start).toISOString(),sum:1250}],'Wh').get(start),1.25);
assert.equal(h.points([{start:start,sum:1500}],'Wh').get(start),1.5,'websocket unix-ms timestamp supported');
const partial=h.points(samples.filter(x=>x.start!==new Date(start+5*one).toISOString()),'kWh');
assert.equal(h.peak(partial,start,start+one*6),null,'missing one quarter suppresses entire period maximum');
assert.equal(h.bounds('2026-11-30','2026-11-31'),null,'invalid calendar date rejected');
assert.equal(h.bounds('2026-11-04','2026-11-03'),null,'reversed interval rejected');
assert.match(src,/class="history-live selected"/);
assert.match(src,/class="history-picker"/);
assert.match(src,/class="history-prev history-nav"/);
assert.match(src,/class="history-next history-nav"/);
assert.match(src,/overlay\.className='history-overlay'/);
assert.match(src,/class="history-ok"/);
assert.match(src,/class="history-cancel"/);
assert.match(src,/overlay\.querySelector\('h3'\)\.focus/,'focus heading instead of input/dropdown');
assert.match(src,/this\._historyMode==='history'\?this\._historicalModel\(\):this\._compute\(\)/);
assert.match(src,/\.quarter-row\{/);
assert.match(src,/Max\. 15-Min\.-Netzbezug/);
assert.match(src,/if\(this\._historyMode==='live'\)this\._maybeLivePeak\(\)/);
const beginning=Date.parse('2026-01-01T00:00:00.000Z');
const today=Date.parse('2026-11-04T16:30:00.000Z');
const h0=new Map(),h1=new Map([[beginning,500]]);
const endStats=new Map([[today-5400000,6200]]); // 15:00 bucket completes at 16:00, before 16:30
assert.equal(h.verified(h0,endStats,null,beginning,today),null,'missing full boundary does not invent annual energy');
const partialYear=h.verified(h1,endStats,null,beginning,today);
assert.equal(partialYear.kwh,5700,'first hour fallback uses measured start instead of implicit 0');
assert.equal(partialYear.partialStart,true,'the 1h gap must be labelled partial');
const fullYear=h.verified(new Map([[beginning-3600000,480]]),endStats,null,beginning,today);
assert.equal(fullYear.kwh,5720,'exact year boundary subtracts recorded actual baseline');
assert.equal(fullYear.partialStart,false,'previous hour is complete baseline');
assert.equal(h.verified(new Map([[beginning+3600000,1]]),endStats,null,beginning,today),null,'late start must not silently invent January');
assert.equal(h.verified(new Map([[beginning-3600000,8000]]),endStats,null,beginning,today),null,'negative counter difference rejected');
const fine=new Map([[today-300000,6201]]);
const recent=h.verified(new Map([[beginning-3600000,480]]),endStats,fine,beginning,today);
assert.equal(recent.kwh,5721,'newest complete five-minute sum used for open current day');
console.log('Historical date, fixed-quarter peak and dialog regression checks passed');
