// Regression checks for the editor-side +/- consumer manager and persistence.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const code = fs.readFileSync(path.join(__dirname,'..','custom_components','smartify_flow_card','frontend','smartify-flow-card.js'),'utf8');
assert.match(code, /_consumerList\(section\) \{/, 'consumer editor manager exists');
assert.match(code, /consumer-manager-add/, 'plus button exists');
assert.match(code, /consumer-manager-minus/, 'minus button exists');
assert.match(code, /edit\.addEventListener\('click', \(\) => open\(id\)\)/, 'minus opens editing, not immediate deletion');
assert.match(code, /dialog\.setAttribute\('role', 'dialog'\)/, 'accessible popup');
assert.match(code, /Leistungssensor \(W\/kW\/MW\)/, 'editable power entity');
assert.match(code, /Gesamtenergiezähler \(Wh\/kWh\/MWh, optional\)/, 'editable energy sensor');
assert.match(code, /Anzeigename/, 'name editable');
assert.match(code, /Gerätefarbe \(HEX\/CSS\)/, 'color editable');
assert.match(code, /Icon \(mit Symbolvorschau\)/, 'icon editable with suggestions');
assert.match(code, /this\._matchingEntities\('power'\)\.some\(option => option\.id === nextId\)/, 'reject invalid power sensors');
assert.match(code, /delete this\._config\.consumers\[id\]/, 'old entity mapping can be changed or removed');
assert.match(code, /window\.confirm\(/, 'deletion requires confirmation');
assert.match(code, /excluded_consumers/, 'label-discovered consumers can be excluded without reappearing');
assert.match(code, /close\(\); render\(\); this\._emit\(\)/, 'only commit after user saves or confirms deletion');
assert.match(code, /\.filter\(id => !excluded\.has\(id\)\)/, 'filter excluded entities in the rendering model');
assert.doesNotMatch(code.slice(code.indexOf('  _consumerList(section) {'),code.indexOf('  _backupSection() {')), /window\.prompt\(/, 'no prompt UI');
assert.match(code, /draftPicker\('entity', [^\n]*'power'/, 'popup uses the real filtered power picker');
assert.match(code, /draftPicker\('energy', [^\n]*'energy'/, 'popup uses the real filtered energy picker');
assert.match(code, /draftPicker\('icon', [^\n]*'icon'/, 'popup uses icon picker with live previews');
assert.match(code, /if \(energyId && !this\._matchingEntities\('energy'\)/, 'invalid energy sensor is rejected on save');
assert.match(code, /onChoose: chosen => \{ current = chosen; \}/, 'popup picker updates draft, not live config');
assert.doesNotMatch(code.slice(code.indexOf('  _consumerList(section) {'),code.indexOf('  _backupSection() {')), /document\.createElement\('datalist'\)/, 'no browser datalist in popup');
const consumerDialog = code.slice(code.indexOf('  _consumerList(section) {'),code.indexOf('  _backupSection() {'));
assert.doesNotMatch(consumerDialog, /entity\.input\.focus\(\)/, 'do not auto-open the power suggestions');
assert.match(consumerDialog, /title\.tabIndex = -1/, 'focusable heading is provided');
assert.match(consumerDialog, /title\.focus\(\{ preventScroll: true \}\)/, 'focus the dialog heading instead of the search picker');
assert.match(code, /input\.addEventListener\('focus', \(\) => \{ this\._closePickers\(obj\); update\(\); \}\)/,
  'suggestions still open when the picker receives user focus');
console.log('Consumer management popup and exclusion checks passed');
