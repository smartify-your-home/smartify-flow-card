const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const src=fs.readFileSync(path.join(__dirname,'..','custom_components','smartify_flow_card','frontend','smartify-flow-card.js'),'utf8');
const i=src.indexOf('function sfcLocalDate('),j=src.indexOf('function sfcHistoryPoints(',i);
assert(i>=0&&j>i);
const helpers=vm.runInNewContext(src.slice(i,j)+'\n({quick:sfcQuickPeriod,validate:sfcValidatePeriod})');
const now=new Date(2026,10,4,15,20);
assert.deepEqual(JSON.parse(JSON.stringify(helpers.quick('day',now))),{start:'2026-11-04',end:'2026-11-04'});
assert.deepEqual(JSON.parse(JSON.stringify(helpers.quick('month',now))),{start:'2026-11-01',end:'2026-11-04'});
assert.deepEqual(JSON.parse(JSON.stringify(helpers.quick('year',now))),{start:'2026-01-01',end:'2026-11-04'});
assert.ok(helpers.validate('2026-10-25','2026-11-04',now),'cross-month supported');
assert.ok(helpers.validate('2025-12-01','2026-02-02',now),'cross-year supported');
assert.ok(helpers.validate('2026-01-01','2026-11-04',now),'year-to-date supported');
assert.equal(helpers.validate('2026-11-05','2026-11-05',now),null,'future day blocked');
assert.equal(helpers.validate('2026-12-01','2026-11-04',now),null,'reversed period blocked');
const partial=helpers.validate('2026-11-04','2026-11-04',now);
assert.equal(partial.to,+now,'today ends at current time, not tomorrow');
assert.equal(partial.isToday,true);
assert.ok(helpers.validate('2024-01-01','2026-11-04',now),'multi-year timeframes supported');
assert.equal(helpers.validate('2010-01-01','2026-11-04',now),null,'bounded long-range queries');
for(const selector of ['history-live','history-date','history-day','history-month','history-year'])
  assert.match(src,new RegExp('class="'+selector+'(?: selected)?"'),'toolbar '+selector);
assert.match(src,/this\._loadHistory\(period\.start,period\.end,mode\)/,'quick shortcuts load immediately');
assert.match(src,/type:'recorder\/statistic_during_period'/,'efficient direct period delta rather than hourly rows');
assert.match(src,/fixed_period:\{start_time:new Date\(range\.from\)\.toISOString\(\),end_time:new Date\(range\.to\)\.toISOString\(\)\}/);
assert.match(src,/overlay\.querySelector\('\.history-cancel'\)\.addEventListener\('click',\(\)=>overlay\.remove\(\)\)/,'dialog cancel');
assert.match(src,/overlay\.remove\(\);this\._loadHistory\(from\.value,end\)/,'dialog loads after OK');
assert.match(src,/const validPeakRange=/,'quarter peak remains separate and bounded');
console.log('Historical quick-day/month/year and cross-calendar range tests passed');
